// Regenerates src/lib/data/google-fonts.ts from Google Fonts' public metadata.
// This runs at development time only; the extension itself never makes network
// requests. Usage:
//   curl -s https://fonts.google.com/metadata/fonts -o gf.json
//   node scripts/gen-google-fonts.mjs gf.json
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/gen-google-fonts.mjs <metadata.json>');
  process.exit(1);
}

// The endpoint may prefix the JSON with an XSSI guard like )]}'
const raw = readFileSync(input, 'utf8').replace(/^\)\]\}'\s*/, '');
const data = JSON.parse(raw);
const list = Array.isArray(data.familyMetadataList) ? data.familyMetadataList : [];

const families = [
  ...new Set(
    list
      .map((entry) => (typeof entry?.family === 'string' ? entry.family.trim() : ''))
      // Only plain family names; reject anything unexpected.
      .filter((name) => /^[A-Za-z0-9 .&'+-]{1,64}$/.test(name)),
  ),
].sort((a, b) => a.localeCompare(b));

if (families.length < 1000) {
  console.error(`Only ${families.length} families found; refusing to overwrite.`);
  process.exit(1);
}

const out = `// Generated by scripts/gen-google-fonts.mjs on ${new Date().toISOString().slice(0, 10)}.
// ${families.length} family names from fonts.google.com. Do not edit by hand.
const RAW = ${JSON.stringify(families.join('\n'))};

export const GOOGLE_FONT_FAMILIES: ReadonlySet<string> = new Set(
  RAW.split('\\n').map((name) => name.toLowerCase()),
);
`;

mkdirSync('src/lib/data', { recursive: true });
writeFileSync('src/lib/data/google-fonts.ts', out);
console.log(`Wrote ${families.length} families to src/lib/data/google-fonts.ts`);
